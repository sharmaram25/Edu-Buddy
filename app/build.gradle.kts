import java.util.Properties

// Release signing comes from an untracked keystore.properties (see README > Signing).
// Without it, release builds fall back to the debug key so they still install for testing.
val keystoreProps: Properties? = rootProject.file("keystore.properties").takeIf { it.exists() }?.let { f ->
    Properties().apply { f.inputStream().use { load(it) } }
}

